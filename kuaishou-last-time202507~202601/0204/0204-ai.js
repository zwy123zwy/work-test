// ==================== 一、AI 基本概念 ====================

// 1. 什么是 LLM（大语言模型）？
// 答：基于 Transformer 架构、在海量文本上预训练的生成式模型，通过预测下一个 token 学习语言规律。典型代表：GPT、Claude、Gemini、Llama 等。支持零样本/少样本学习，可完成文本生成、摘要、翻译、推理等任务。

// 2. 解释 Token 与 Tokenization
// 答：Token 是模型的最小处理单元，可对应字、词或子词。Tokenization 把文本切分为 token 序列。不同模型词表不同，中英混排通常 1 个中文字 ≈ 1–2 token，英文约 4 字符 ≈ 1 token。影响输入长度限制与计费。

// 3. 什么是 Temperature？如何影响生成结果？
// 答：控制采样随机性的超参数，范围通常 0–2。Temperature 低（如 0.2）：输出更确定、重复性高，适合翻译、代码补全；Temperature 高（如 0.9）：更随机、创意性强，适合头脑风暴、续写。0 表示贪心解码（每次取概率最高 token）。

// 4. 什么是 RAG（检索增强生成）？
// 答：检索增强生成。先用检索系统（向量库等）从外部知识库找出与问题相关的文档，再将文档与问题一起交给 LLM 生成回答。可缓解幻觉、降低过时信息，适合企业知识库、客服等场景。

// 5. 什么是 Agent？与普通 LLM 调用有何区别？
// 答：Agent 是具有规划与工具调用能力的 AI 系统，可根据任务选择调用搜索、计算器、API 等工具，并循环执行直到完成目标。普通 LLM 调用多为单次请求-响应；Agent 强调多轮推理与自主决策。

// 6. 什么是 Fine-tuning 与 Prompt Tuning？
// 答：Fine-tuning：在特定数据上微调模型参数，效果好但成本高。Prompt Tuning：只训练少量 prompt 相关参数，冻结主模型，轻量高效。还有 LoRA 等参数高效微调方式，在效果与成本间折中。

// 7. 什么是 Hallucination（幻觉）？如何缓解？
// 答：模型生成看似合理但不符合事实的内容。缓解：① RAG 引入真实文档；② 降低 temperature；③ 要求引用来源；④ 后处理事实核查；⑤ 使用更强的基座模型；⑥ 明确提示「不确定时请说不知道」。

// 8. 什么是 Few-shot 与 Zero-shot？
// 答：Zero-shot：不给示例，直接描述任务让模型执行。Few-shot：在提示中给出少量输入-输出示例，引导模型模仿。Few-shot 通常能显著提升复杂任务效果，但会占用上下文长度。


// ==================== 二、提示词工程化规范 ====================

// 9. 提示词工程化的核心原则有哪些？
// 答：① 角色设定：明确模型身份与能力边界；② 任务清晰：目标、格式、约束用自然语言写清；③ 结构化：用分隔符、列表、示例组织；④ 可复用：抽象为模板，变量参数化；⑤ 可评测：建立测试集，量化效果。

// 10. 什么是 Prompt 模板？如何设计可维护的模板？
// 答：将提示词抽象为带占位符的模板，如 {{role}}、{{task}}、{{examples}}。设计要点：① 变量命名语义化；② 必填与可选分离；③ 版本管理；④ 支持多语言/多场景切换；⑤ 与配置中心或代码仓库统一管理。

// 11. 如何规范 Prompt 的版本管理与变更？
// 答：① 纳入版本控制（Git），记录每次修改及原因；② 建立 A/B 测试流程，对比新旧 Prompt 效果；③ 灰度发布，按流量比例切换；④ 监控指标（准确率、延迟、成本）；⑤ 回滚预案，出问题可快速恢复。

// 12. 提示词中「系统提示」与「用户提示」如何分工？
// 答：系统提示：定义角色、全局规则、输出格式、禁止行为，相对稳定。用户提示：具体任务、上下文、本次输入，随请求变化。系统提示优先控制行为边界，用户提示承载业务内容。二者配合，便于复用与调试。

// 13. 如何编写可评测、可回归的 Prompt？
// 答：① 建立标准测试集：输入 + 期望输出/评分标准；② 使用自动化评测（相似度、关键词、LLM-as-judge）；③ CI 中集成 Prompt 回归，变更前后对比；④ 输出结构化（JSON 等），便于程序化校验；⑤ 记录每次评测结果，追踪趋势。

// 14. 提示词安全与越狱防护有哪些规范？
// 答：① 明确禁止输出有害内容，写入系统提示；② 对用户输入做过滤与长度限制；③ 检测常见越狱模式（角色扮演、忽略指令等）；④ 敏感输出二次审核或脱敏；⑤ 记录异常请求，用于模型与规则迭代。

// 15. 多轮对话场景下如何管理上下文与 Prompt？
// 答：① 控制上下文长度：截断或摘要历史；② 角色分离：系统/用户/助手消息按格式组织；③ 重要信息在首轮或最近几轮保留；④ 长对话可分段摘要再注入；⑤ 明确「对话重置」规则，避免上下文污染。


// ==================== 三、最新工程规范与实践 ====================

// 16. AI 应用的观测与可观测性包括哪些？
// 答：① 日志：请求/响应、token 用量、模型与参数；② 指标：延迟、QPS、错误率、成本；③ 链路追踪：请求从入口到模型调用的全链路；④ 告警：异常延迟、错误率、配额超限；⑤ 调试工具：Prompt 回放、效果分析。

// 17. 模型选型与路由的工程实践？
// 答：① 按任务类型选择模型（简单 vs 复杂、低成本 vs 高精度）；② 路由策略：规则路由（如按语言）或模型路由（小模型优先，失败再切大模型）；③ 降级策略：主模型不可用时自动切换备用；④ 成本与效果平衡，建立选型矩阵。

// 18. AI 应用的测试策略有哪些？
// 答：① 单元测试：Mock 模型接口，验证业务逻辑；② 集成测试：小批量真实调用，验证链路；③ 评测集：覆盖典型输入，对比期望输出；④ 回归测试：Prompt/模型变更后自动跑评测；⑤ 红队测试：模拟恶意输入，验证安全与合规。

// 19. 什么是 Responsible AI？工程上如何落地？
// 答：负责任的 AI：公平、可解释、隐私、安全、透明。落地：① 数据与模型文档化；② 输出可解释（如引用来源）；③ 人工审核高风险场景；④ 用户知情与同意；⑤ 建立投诉与反馈机制；⑥ 定期审计与合规检查。

// 20. AI 工程中的成本优化有哪些手段？
// 答：① 模型选型：简单任务用便宜模型；② 缓存：相同/相似请求复用结果；③ 输出长度限制（max_tokens）；④ 提示压缩：去除冗余，保留关键信息；⑤ 批量请求；⑥ 自建/本地部署 vs 云 API 的性价比评估；⑦ 监控 token 消耗，设置预算与告警。
