// ==================== 一、传统前端八股 ====================

// 1. 什么是闭包？有什么优缺点？
// 答：闭包是函数能访问其词法作用域外的变量。函数 A 返回函数 B，B 引用了 A 的作用域变量，形成闭包。
// 优点：数据私有、柯里化、模块化。缺点：内存泄漏（变量不会被回收）、过度使用影响性能。

// 2. 解释 Event Loop（事件循环）
// 答：JS 单线程，通过事件循环处理异步。宏任务（script、setTimeout、setInterval、I/O）与微任务（Promise.then、queueMicrotask、MutationObserver）交替执行；
// 每轮宏任务后清空微任务队列，再取下一个宏任务。微任务优先于宏任务。

// 3. HTTP 与 HTTPS 的区别？
// 答：HTTPS = HTTP + TLS/SSL 加密。区别：端口 80 vs 443；数据明文 vs 加密；HTTPS 需要证书、防窃听与篡改、利于 SEO。

// 4. 强缓存与协商缓存的区别？
// 答：强缓存（Cache-Control、Expires）不发请求直接读本地；协商缓存（Last-Modified/If-Modified-Since、ETag/If-None-Match）发请求，304 用本地。优先级：强缓存 > 协商缓存。

// 5. 跨域是什么？如何解决？
// 答：同源策略限制：协议、域名、端口任一不同即跨域。解决：CORS、JSONP、代理、postMessage、nginx 反向代理。

// 6. 什么是虚拟 DOM？优缺点？
// 答：用 JS 对象描述真实 DOM，通过 diff 算出最小变更再批量更新。优点：减少 DOM 操作、跨平台；缺点：首次渲染和 diff 有开销，极简单页面未必更快。

// 7. 解释 TCP 三次握手和四次挥手
// 答：三次握手：SYN → SYN-ACK → ACK，建立连接。四次挥手：FIN → ACK → FIN → ACK，双方各自关闭，保证数据发完。

// 8. 回流（Reflow）与重绘（Repaint）的区别？
// 答：回流：几何属性变化导致布局重算；重绘：外观变化（颜色等）不改变布局。回流一定触发重绘，重绘不一定回流。避免：批量改 DOM、用 transform 代替 top/left。

// 9. 前端性能优化有哪些手段？
// 答：资源压缩、懒加载、CDN、雪碧图、防抖节流、虚拟列表、骨架屏、SSR、代码分割、Tree Shaking、缓存策略、减少重排重绘。

// 10. 解释 XSS 与 CSRF
// 答：XSS：恶意脚本注入，执行窃取信息等。防护：转义、CSP、HttpOnly。CSRF：伪造用户请求。防护：Token、SameSite、Referer 校验。


// ==================== 二、AI 基本应用规范 ====================

// 11. 前端接入 AI 接口时要注意哪些安全规范？
// 答：① 不在前端暴露 API Key，由后端代理转发；② 对用户输入做校验和长度限制，防注入；③ 敏感数据脱敏后再发；④ 使用 HTTPS；⑤ 记录日志便于审计。

// 12. 前端调用 AI 接口时如何做限流与降级？
// 答：① 前端防抖/节流，避免高频调用；② 后端限流（如令牌桶）；③ 队列排队、超时重试；④ 降级：AI 失败时回退到规则或缓存结果；⑤ 展示 loading/骨架屏，防止重复点击。

// 13. AI 生成内容的版权与合规问题如何考虑？
// 答：① 明确 AI 生成内容的版权归属与使用范围；② 对敏感领域（医疗、法律等）加人工审核；③ 标注「AI 辅助生成」；④ 遵循平台与地区法规，避免生成违规内容。

// 14. 前端如何设计 AI 对话/智能助手的交互规范？
// 答：① 明确展示「AI 回答」身份，避免误导；② 支持复制、引用、反馈（点赞/点踩）；③ 流式输出时做打字机效果；④ 超长回答折叠或分页；⑤ 提供重新生成、停止生成。

// 15. 前端与 AI 联调时有哪些常见约定？
// 答：① 统一请求格式（prompt、temperature、max_tokens 等）；② 统一响应结构（content、usage、error_code）；③ 流式用 SSE 或 WebSocket；④ 约定错误码与重试策略；⑤ 前端做超时与异常提示。


// ==================== 三、覆盖面 / 解释题 ====================

// 16. 解释 React 与 Vue 的响应式原理差异
// 答：Vue2：Object.defineProperty 劫持 get/set；Vue3：Proxy 代理整个对象。React：依靠 setState 触发更新，不可变数据，通过 diff 决定更新范围。

// 17. 什么是 BFC？如何触发？
// 答：块级格式化上下文，独立布局区域。触发：float≠none、position 为 absolute/fixed、display 为 inline-block/flex/grid、overflow≠visible 等。常用于清除浮动、防止 margin 塌陷。

// 18. 解释 ES Module 与 CommonJS 的区别
// 答：ESM 静态导入、编译时确定依赖、支持 tree shaking、顶层 await；CJS 动态 require、运行时加载、默认同步。Node 支持 ESM（type: module），两者可互操作。

// 19. 什么是首屏时间？如何优化？
// 答：首屏时间：用户看到首屏内容的时间。优化：SSR/预渲染、关键 CSS 内联、资源预加载、懒加载非首屏、减少阻塞、CDN、骨架屏。

// 20. 前端工程化通常包含哪些部分？
// 答：构建（Vite/Webpack）、模块化（ESM）、打包与代码分割、Lint/格式化、单元测试、CI/CD、规范（目录、命名、提交）、监控与埋点、文档与组件库。
